import { createHash } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { CONFUSABLES_COUNT, GENERATED_CONFUSABLES } from './confusables';
import { TOP_BRANDS, TOP_BRANDS_COUNT, TOP_BRANDS_SHA256 } from './top-brands';
import { parseDomain } from '../domain';

const read = (name: string) => readFileSync(join(process.cwd(), 'src', 'detection', 'data', name), 'utf8');

describe('generated confusables', () => {
  it('has a header with source, version, terms and licence', () => {
    const head = read('confusables.ts').slice(0, 1200);
    expect(head).toContain('GENERATED by scripts/gen-confusables.mjs');
    expect(head).toContain('https://www.unicode.org/Public/security/latest/confusables.txt');
    expect(head).toMatch(/Unicode \d+\.\d+\.\d+/);
    expect(head).toContain('Unicode License v3');
  });

  it('maps single non-ASCII characters to 1 to 2 Latin letters or digits', () => {
    const entries = Object.entries(GENERATED_CONFUSABLES);
    expect(entries.length).toBe(CONFUSABLES_COUNT);
    for (const [source, target] of entries) {
      expect([...source]).toHaveLength(1);
      expect(source.codePointAt(0) ?? 0).toBeGreaterThan(0x7f);
      expect(target).toMatch(/^[a-z0-9]{1,2}$/);
    }
  });
});

describe('generated famous-site list', () => {
  it('has a header with source, licence, date, count and hash', () => {
    const head = read('top-brands.ts').slice(0, 1400);
    expect(head).toContain('GENERATED by scripts/gen-brands.mjs');
    expect(head).toContain('Creative Commons Attribution 3.0');
    expect(head).toContain('https://creativecommons.org/licenses/by/3.0/');
    expect(head).toMatch(/Date:\s+\d{4}-\d{2}-\d{2}/);
  });

  it('matches its recorded count and SHA-256', () => {
    expect(TOP_BRANDS).toHaveLength(TOP_BRANDS_COUNT);
    expect(createHash('sha256').update(TOP_BRANDS.join('\n'), 'utf8').digest('hex')).toBe(TOP_BRANDS_SHA256);
  });

  it('holds registrable domains only, and none from the deny-list', () => {
    for (const domain of TOP_BRANDS) expect(parseDomain(domain).registrable).toBe(domain);
    for (const banned of ['pornhub.com', 'doubleclick.net', 'bit.ly', 'cloudfront.net']) {
      expect(TOP_BRANDS).not.toContain(banned);
    }
  });
});