// Regenerates src/detection/data/confusables.ts from Unicode confusables.txt.
// Dev-time only (uses fetch). Run: npm run gen:confusables
// Keeps only mappings whose source is ONE non-ASCII character and whose target is 1 to 2 Latin letters or digits.
import { renameSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_URL = 'https://www.unicode.org/Public/security/latest/confusables.txt';
const LICENSE_URL = 'https://www.unicode.org/license.txt';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'detection', 'data', 'confusables.ts');

const fail = (message) => {
  console.error(`gen-confusables: ${message}. The committed file was not changed.`);
  process.exit(1);
};

let text;
try {
  const response = await fetch(SOURCE_URL);
  if (!response.ok) fail(`download failed with status ${response.status}`);
  text = await response.text();
} catch (error) {
  fail(`download failed (${error instanceof Error ? error.message : 'unknown error'})`);
}

const lines = text.split(/\r?\n/);
const header = lines.filter((l) => l.startsWith('#')).slice(0, 12);
const copyright = header.find((l) => /©|copyright/i.test(l));
const terms = header.find((l) => /terms_of_use|license/i.test(l));
if (!copyright || !terms) fail('the file header has no copyright or terms line');
const ascii = (line) => line.replace(/^#\s*/, '').replace(/©/g, '(c)').replace(/®/g, '(R)');
const date = /Date:\s*(.+)/.exec(header.join('\n'))?.[1]?.trim() ?? 'unknown';
const version = /Version:\s*(\S+)/.exec(header.join('\n'))?.[1] ?? 'unknown';

/** @type {Map<string, string>} */
const kept = new Map();
for (const line of lines) {
  if (line === '' || line.startsWith('#')) continue;
  const [sourceField, targetField] = line.split(';').map((f) => f.trim());
  if (!sourceField || !targetField) continue;
  const sourceCps = sourceField.split(/\s+/).map((h) => parseInt(h, 16));
  if (sourceCps.length !== 1 || Number.isNaN(sourceCps[0]) || sourceCps[0] <= 0x7f) continue;
  const source = String.fromCodePoint(sourceCps[0]);
  // The engine lower-cases and NFKC-normalises text before it looks characters up, so only such keys can ever match.
  if (source.normalize('NFKC').toLowerCase() !== source) continue;
  const target = targetField
    .split(/\s+/)
    .map((h) => String.fromCodePoint(parseInt(h, 16)))
    .join('')
    .toLowerCase();
  if (!/^[a-z0-9]{1,2}$/.test(target)) continue;
  kept.set(source, target);
}
// Fixed point: drop an entry whose target contains any kept source key (targets are ASCII, so this is a safety net).
for (const [source, target] of kept) {
  if ([...kept.keys()].some((key) => target.includes(key))) kept.delete(source);
}
if (kept.size < 300) fail(`only ${kept.size} entries were found, which is far fewer than expected`);

/** @type {Map<string, string[]>} */
const groups = new Map();
for (const [source, target] of kept) {
  groups.set(target, [...(groups.get(target) ?? []), source]);
}
const body = [...groups.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([target, sources]) => {
    const escaped = sources
      .map((s) => s.codePointAt(0))
      .sort((a, b) => a - b)
      .map((cp) => `\\u{${cp.toString(16)}}`)
      .join('');
    return `  ${/^\d/.test(target) ? `'${target}'` : target}: '${escaped}',`;
  })
  .join('\n');

const out = `/**
 * GENERATED by scripts/gen-confusables.mjs. Do not edit by hand; run \`npm run gen:confusables\`.
 *
 * Source:   ${SOURCE_URL}
 * Version:  Unicode ${version}, file date ${date}
 * Terms:    ${ascii(copyright)}
 *           ${ascii(terms)}
 * Licence:  Unicode License v3, ${LICENSE_URL} (text in public/licenses/unicode-license-v3.txt)
 * Content:  ${kept.size} single-character mappings (non-ASCII source to 1 to 2 Latin letters or digits), grouped by target.
 *           Sources are written as \\u{...} escapes so no look-alike character sits in this file.
 */
const GROUPS: Readonly<Record<string, string>> = {
${body}
};

export const CONFUSABLES_UNICODE_VERSION = '${version}';
export const CONFUSABLES_COUNT = ${kept.size};

/** Source character to the Latin letters or digits it imitates. */
export const GENERATED_CONFUSABLES: Readonly<Record<string, string>> = (() => {
  const map: Record<string, string> = {};
  for (const [target, sources] of Object.entries(GROUPS)) {
    for (const source of sources) map[source] = target;
  }
  return map;
})();
`;

const tmp = `${OUT}.tmp`;
writeFileSync(tmp, out);
renameSync(tmp, OUT);
console.log(`Wrote ${OUT}: ${kept.size} entries, Unicode ${version}, ${date}`);
