// Regenerates src/detection/data/top-brands.ts: the most visited registrable domains, used to spot typosquats.
// Dev-time only (uses fetch). Run: npm run gen:brands            (default top 1000)
//                                 npm run gen:brands -- --top 500 (any integer from 100 to 5000)
// Source: Majestic Million, licensed under CC BY 3.0 (https://creativecommons.org/licenses/by/3.0/).
// Tranco is NOT used: its terms are unclear for redistribution (see THIRD_PARTY_NOTICES.md).
import { createHash } from 'node:crypto';
import { renameSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getDomain } from 'tldts';

const SOURCE_URL = 'https://downloads.majestic.com/majestic_million.csv';
const LICENSE_PAGE = 'https://majestic.com/reports/majestic-million';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'detection', 'data', 'top-brands.ts');

/**
 * Domains removed BEFORE the cut, so the list never names them in a warning: adult sites, ad and tracking
 * networks, URL shorteners and plain infrastructure. The count dropped is printed on every run.
 */
export const EXCLUDE = new Set([
  'pornhub.com', 'xvideos.com', 'xnxx.com', 'xhamster.com', 'redtube.com', 'youporn.com', 'chaturbate.com', 'onlyfans.com',
  'doubleclick.net', 'googlesyndication.com', 'googleadservices.com', 'adnxs.com', 'criteo.com', 'taboola.com', 'outbrain.com',
  'scorecardresearch.com', 'quantserve.com', 'adsrvr.org', 'rubiconproject.com', 'pubmatic.com', 'openx.net',
  'bit.ly', 'tinyurl.com', 't.co', 'goo.gl', 'ow.ly', 'is.gd', 'buff.ly', 'rebrand.ly', 'cutt.ly',
  'akamaihd.net', 'akamaized.net', 'cloudfront.net', 'amazonaws.com', 'googleusercontent.com', 'gstatic.com', 'fbcdn.net',
  'azureedge.net', 'edgekey.net', 'fastly.net', 'cdn77.org', 'root-servers.net', 'gtld-servers.net',
]);

const args = process.argv.slice(2);
const topIndex = args.indexOf('--top');
const top = topIndex >= 0 ? Number(args[topIndex + 1]) : 1000;
const fail = (message) => {
  console.error(`gen-brands: ${message}. The committed file was not changed.`);
  process.exit(1);
};
if (!Number.isInteger(top) || top < 100 || top > 5000) fail('--top must be an integer from 100 to 5000');

const kept = [];
let dropped = 0;
try {
  const response = await fetch(SOURCE_URL);
  if (!response.ok || !response.body) fail(`download failed with status ${response.status}`);
  const decoder = new TextDecoder();
  let rest = '';
  let first = true;
  read: for await (const chunk of response.body) {
    rest += decoder.decode(chunk, { stream: true });
    const lines = rest.split('\n');
    rest = lines.pop() ?? '';
    for (const line of lines) {
      if (first) {
        first = false;
        if (!line.startsWith('GlobalRank,TldRank,Domain')) fail('unexpected CSV header');
        continue;
      }
      const domain = line.split(',')[2]?.trim().toLowerCase();
      if (!domain || !/^[a-z0-9.-]+$/.test(domain)) continue;
      // Keep registrable domains only (play.google.com is not one), judged with the Public Suffix List.
      if (getDomain(domain, { allowPrivateDomains: false }) !== domain || kept.includes(domain)) continue;
      if (EXCLUDE.has(domain)) {
        dropped += 1;
        continue;
      }
      kept.push(domain);
      if (kept.length >= top) break read;
    }
  }
} catch (error) {
  fail(`download failed (${error instanceof Error ? error.message : 'unknown error'})`);
}
if (kept.length < top) fail(`only ${kept.length} rows were read`);

const hash = createHash('sha256').update(kept.join('\n'), 'utf8').digest('hex');
const date = new Date().toISOString().slice(0, 10);
const lines = [];
let current = '';
for (const domain of kept) {
  if (current.length + domain.length + 1 > 100) {
    lines.push(current);
    current = '';
  }
  current = current === '' ? domain : `${current} ${domain}`;
}
if (current !== '') lines.push(current);

const out = `/**
 * GENERATED by scripts/gen-brands.mjs. Do not edit by hand; run \`npm run gen:brands\`.
 *
 * Source:   Majestic Million, ${SOURCE_URL}
 * Licence:  Licensed under a Creative Commons Attribution 3.0 Unported License (read on ${LICENSE_PAGE} on ${date}).
 *           Majestic subset licensed under CC BY 3.0, https://creativecommons.org/licenses/by/3.0/
 *           Attribution: Majestic (https://majestic.com), Majestic Million.
 * Date:     ${date}
 * Count:    ${kept.length} registrable domains (top ${top}, most visited first), ${dropped} dropped by the EXCLUDE deny-list
 * SHA-256:  ${hash}
 *           (of the kept domains joined with a newline, UTF-8)
 */
export const TOP_BRANDS_COUNT = ${kept.length};
export const TOP_BRANDS_SHA256 = '${hash}';

export const TOP_BRANDS: readonly string[] = [
${lines.map((l) => `  '${l}',`).join('\n')}
]
  .join(' ')
  .split(' ');
`;
const tmp = `${OUT}.tmp`;
writeFileSync(tmp, out);
renameSync(tmp, OUT);
console.log(`Wrote ${OUT}: ${kept.length} domains, ${dropped} dropped by EXCLUDE, sha256 ${hash.slice(0, 12)}...`);
